package com.ptit.muonphong.entity;

import java.io.Serializable;
import java.time.LocalDate;

public abstract class NguoiDung implements Serializable {
    private static final long serialVersionUID = 1L;

    private int id;
    private String tenDangNhap;
    private String matKhau;
    private String hoTen;
    private String diaChi;
    private LocalDate ngaySinh;
    private String email;
    private String soDienThoai;
    private String trangThai;

    public abstract String getVaiTroCode();

    public abstract String getVaiTroDisplay();

    public boolean isHoatDong() {
        return "Hoạt động".equalsIgnoreCase(trangThai);
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getTenDangNhap() {
        return tenDangNhap;
    }

    public void setTenDangNhap(String tenDangNhap) {
        this.tenDangNhap = tenDangNhap;
    }

    public String getMatKhau() {
        return matKhau;
    }

    public void setMatKhau(String matKhau) {
        this.matKhau = matKhau;
    }

    public String getHoTen() {
        return hoTen;
    }

    public void setHoTen(String hoTen) {
        this.hoTen = hoTen;
    }

    public String getDiaChi() {
        return diaChi;
    }

    public void setDiaChi(String diaChi) {
        this.diaChi = diaChi;
    }

    public LocalDate getNgaySinh() {
        return ngaySinh;
    }

    public void setNgaySinh(LocalDate ngaySinh) {
        this.ngaySinh = ngaySinh;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getSoDienThoai() {
        return soDienThoai;
    }

    public void setSoDienThoai(String soDienThoai) {
        this.soDienThoai = soDienThoai;
    }

    public String getTrangThai() {
        return trangThai;
    }

    public void setTrangThai(String trangThai) {
        this.trangThai = trangThai;
    }
}
